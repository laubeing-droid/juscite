function frontmatterTriggers() {
  const line = (key) => DRAFT_SKILL_FRONTMATTER.split("\n").find((l) => l.startsWith(key + ":"))?.slice(key.length + 1).trim() ?? "";
  const list = (s) => s ? s.split(",").map((x) => x.trim()).filter(Boolean).map((x) => (x.startsWith("/") ? x : "." + x)) : [];
  return {
    commands: line("commands") ? line("commands").split(/[,\s]+/).filter(Boolean) : [],
    promptPatterns: line("patterns") ? [line("patterns")] : [],
    fileTypes: list(line("fileTypes")),
  };
}
